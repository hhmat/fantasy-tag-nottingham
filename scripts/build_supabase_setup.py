#!/usr/bin/env python3
"""Rebuild the all-in-one SQL setup from ordered migrations and seed data."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUPABASE = ROOT / "supabase"
migrations = sorted((SUPABASE / "migrations").glob("*.sql"))
if not migrations:
    raise SystemExit("No migrations found")

header = f"""-- ============================================================================
-- Fantasy Tag Nottingham — ALL-IN-ONE SETUP
-- Paste this entire file into the Supabase SQL Editor and click Run.
-- (Combines migrations 0001-{migrations[-1].name[:4]} + real-season seed data)
-- Generated by scripts/build_supabase_setup.py; do not edit generated sections.
-- For new projects only. Existing projects apply individual migrations in order.
-- ============================================================================

"""
parts = [header]
for migration in migrations:
    parts.append(migration.read_text(encoding="utf-8").strip() + "\n\n")
parts.append((SUPABASE / "seed.sql").read_text(encoding="utf-8").strip() + "\n")
(SUPABASE / "SETUP.sql").write_text("".join(parts), encoding="utf-8")
print(f"Rebuilt supabase/SETUP.sql through {migrations[-1].name}")
